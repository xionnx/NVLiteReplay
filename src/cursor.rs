impl DxgiCursorCompositor {
    pub unsafe fn new(device: &ID3D11Device) -> Option<Self> {
        let mut vs = None;
        device.CreateVertexShader(CURSOR_VS_DXBC, None, Some(&mut vs)).ok()?;
        let vs = vs?;

        let mut ps = None;
        device.CreatePixelShader(CURSOR_PS_DXBC, None, Some(&mut ps)).ok()?;
        let ps = ps?;

        let rdesc = D3D11_RASTERIZER_DESC {
            FillMode: D3D11_FILL_SOLID,
            CullMode: D3D11_CULL_NONE,
            DepthClipEnable: false.into(),
            ..Default::default()
        };
        let mut rs = None;
        device.CreateRasterizerState(&rdesc, Some(&mut rs)).ok()?;
        let rs = rs?;

        let cdesc = D3D11_BUFFER_DESC {
            ByteWidth: std::mem::size_of::<CursorCb>() as u32,
            Usage: D3D11_USAGE_DEFAULT,
            BindFlags: D3D11_BIND_CONSTANT_BUFFER.0 as u32,
            ..Default::default()
        };
        let mut cb = None;
        device.CreateBuffer(&cdesc, None, Some(&mut cb)).ok()?;
        let cb = cb?;

        let mut comp = Self {
            vs,
            ps,
            rs,
            cb,
            cur_tex: None,
            cur_srv: None,
            cur_tex_w: 0,
            cur_tex_h: 0,
            bg_tex: None,
            bg_srv: None,
            bg_tex_w: 0,
            bg_tex_h: 0,
            raw_shape_buf: Vec::with_capacity(64 * 64 * 4),
            norm_rgba: Vec::with_capacity(64 * 64 * 4),
            shape_w: 0,
            shape_h: 0,
            shape_kind: 0,
            has_shape: false,
            visible: false,
            pos_x: 0,
            pos_y: 0,
            seen_dxgi_mouse: false,
        };
        comp.ensure_bg_patch(device, 256, 256);
        Some(comp)
    }

    pub fn on_duplication_reset(&mut self) {
        self.seen_dxgi_mouse = false;
    }

    unsafe fn ensure_bg_patch(&mut self, device: &ID3D11Device, w: u32, h: u32) -> bool {
        if self.bg_tex.is_some() && self.bg_tex_w >= w && self.bg_tex_h >= h {
            return true;
        }
        let tw = w.max(256);
        let th = h.max(256);
        let desc = D3D11_TEXTURE2D_DESC {
            Width: tw,
            Height: th,
            MipLevels: 1,
            ArraySize: 1,
            Format: DXGI_FORMAT_B8G8R8A8_UNORM,
            SampleDesc: DXGI_SAMPLE_DESC { Count: 1, Quality: 0 },
            Usage: D3D11_USAGE_DEFAULT,
            BindFlags: D3D11_BIND_SHADER_RESOURCE.0 as u32,
            ..Default::default()
        };
        let mut tex = None;
        if device.CreateTexture2D(&desc, None, Some(&mut tex)).is_err() {
            return false;
        }
        let Some(tex) = tex else { return false; };
        let sdesc = D3D11_SHADER_RESOURCE_VIEW_DESC {
            Format: DXGI_FORMAT_B8G8R8A8_UNORM,
            ViewDimension: D3D11_SRV_DIMENSION_TEXTURE2D,
            Anonymous: windows::Win32::Graphics::Direct3D11::D3D11_SHADER_RESOURCE_VIEW_DESC_0 {
                Texture2D: windows::Win32::Graphics::Direct3D11::D3D11_TEX2D_SRV {
                    MostDetailedMip: 0,
                    MipLevels: 1,
                },
            },
        };
        let mut srv = None;
        if device.CreateShaderResourceView(&tex, Some(&sdesc), Some(&mut srv)).is_err() {
            return false;
        }
        self.bg_tex = Some(tex);
        self.bg_srv = srv;
        self.bg_tex_w = tw;
        self.bg_tex_h = th;
        self.bg_srv.is_some()
    }

    unsafe fn upload_cursor_texture(
        &mut self,
        device: &ID3D11Device,
        context: &ID3D11DeviceContext,
        w: u32,
        h: u32,
        kind: u32,
    ) {
        if w == 0 || h == 0 || self.norm_rgba.len() < (w * h * 4) as usize {
            return;
        }
        if self.cur_tex.is_none() || self.cur_tex_w != w || self.cur_tex_h != h {
            self.cur_tex = None;
            self.cur_srv = None;
            let desc = D3D11_TEXTURE2D_DESC {
                Width: w,
                Height: h,
                MipLevels: 1,
                ArraySize: 1,
                Format: DXGI_FORMAT_B8G8R8A8_UNORM,
                SampleDesc: DXGI_SAMPLE_DESC { Count: 1, Quality: 0 },
                Usage: D3D11_USAGE_DEFAULT,
                BindFlags: D3D11_BIND_SHADER_RESOURCE.0 as u32,
                ..Default::default()
            };
            let init = D3D11_SUBRESOURCE_DATA {
                pSysMem: self.norm_rgba.as_ptr() as *const _,
                SysMemPitch: w * 4,
                SysMemSlicePitch: w * h * 4,
            };
            let mut tex = None;
            if device.CreateTexture2D(&desc, Some(&init), Some(&mut tex)).is_ok() {
                if let Some(ref t) = tex {
                    let sdesc = D3D11_SHADER_RESOURCE_VIEW_DESC {
                        Format: DXGI_FORMAT_B8G8R8A8_UNORM,
                        ViewDimension: D3D11_SRV_DIMENSION_TEXTURE2D,
                        Anonymous:
                            windows::Win32::Graphics::Direct3D11::D3D11_SHADER_RESOURCE_VIEW_DESC_0 {
                                Texture2D:
                                    windows::Win32::Graphics::Direct3D11::D3D11_TEX2D_SRV {
                                        MostDetailedMip: 0,
                                        MipLevels: 1,
                                    },
                            },
                    };
                    let mut srv = None;
                    if device.CreateShaderResourceView(t, Some(&sdesc), Some(&mut srv)).is_ok() {
                        self.cur_tex = tex;
                        self.cur_srv = srv;
                        self.cur_tex_w = w;
                        self.cur_tex_h = h;
                    }
                }
            }
        } else if let Some(ref tex) = self.cur_tex {
            context.UpdateSubresource(
                tex,
                0,
                None,
                self.norm_rgba.as_ptr() as *const _,
                w * 4,
                0,
            );
        }
        self.shape_w = w;
        self.shape_h = h;
        self.shape_kind = kind;
        self.has_shape = self.cur_srv.is_some();
    }

    pub unsafe fn update_from_dxgi(
        &mut self,
        dupl: &IDXGIOutputDuplication,
        frame_info: &DXGI_OUTDUPL_FRAME_INFO,
        device: &ID3D11Device,
        context: &ID3D11DeviceContext,
    ) {
        if frame_info.LastMouseUpdateTime == 0 {
            return;
        }
        self.seen_dxgi_mouse = true;
        self.visible = frame_info.PointerPosition.Visible.as_bool();
        self.pos_x = frame_info.PointerPosition.Position.x;
        self.pos_y = frame_info.PointerPosition.Position.y;

        let req_size = frame_info.PointerShapeBufferSize as usize;
        if req_size == 0 {
            return;
        }
        if self.raw_shape_buf.len() < req_size {
            self.raw_shape_buf.resize(req_size, 0);
        }
        let mut actual_size = 0u32;
        let mut sinfo = DXGI_OUTDUPL_POINTER_SHAPE_INFO::default();
        if dupl
            .GetFramePointerShape(
                self.raw_shape_buf.len() as u32,
                self.raw_shape_buf.as_mut_ptr() as *mut _,
                &mut actual_size,
                &mut sinfo,
            )
            .is_err()
        {
            return;
        }

        let w = sinfo.Width;
        let pitch = sinfo.Pitch as usize;
        let stype = sinfo.Type as i32;

        if stype == DXGI_OUTDUPL_POINTER_SHAPE_TYPE_COLOR.0
            || stype == DXGI_OUTDUPL_POINTER_SHAPE_TYPE_MASKED_COLOR.0
        {
            let h = sinfo.Height;
            if w == 0 || h == 0 || pitch < (w as usize * 4) {
                return;
            }
            let needed_raw = pitch * (h as usize);
            if actual_size < needed_raw as u32 {
                return;
            }
            self.norm_rgba.resize((w * h * 4) as usize, 0);
            for y in 0..(h as usize) {
                let src = &self.raw_shape_buf[y * pitch..y * pitch + (w as usize) * 4];
                let dst = &mut self.norm_rgba[y * (w as usize) * 4..(y + 1) * (w as usize) * 4];
                dst.copy_from_slice(src);
            }
            let kind = if stype == DXGI_OUTDUPL_POINTER_SHAPE_TYPE_MASKED_COLOR.0 {
                2
            } else {
                0
            };
            self.upload_cursor_texture(device, context, w, h, kind);
        } else if stype == DXGI_OUTDUPL_POINTER_SHAPE_TYPE_MONOCHROME.0 {
            let h = sinfo.Height / 2;
            if w == 0 || h == 0 || pitch < ((w as usize + 7) / 8) {
                return;
            }
            let needed_raw = pitch * (h as usize) * 2;
            if actual_size < needed_raw as u32 {
                return;
            }
            self.norm_rgba.resize((w * h * 4) as usize, 0);
            for y in 0..(h as usize) {
                let and_row = &self.raw_shape_buf[y * pitch..y * pitch + pitch];
                let xor_row = &self.raw_shape_buf[(y + h as usize) * pitch..(y + h as usize) * pitch + pitch];
                for x in 0..(w as usize) {
                    let bit = 0x80u8 >> (x & 7);
                    let and_on = (and_row[x >> 3] & bit) != 0;
                    let xor_on = (xor_row[x >> 3] & bit) != 0;
                    let c = if xor_on { 255u8 } else { 0u8 };
                    let a = if and_on { 255u8 } else { 0u8 };
                    let di = (y * (w as usize) + x) * 4;
                    self.norm_rgba[di] = c;
                    self.norm_rgba[di + 1] = c;
                    self.norm_rgba[di + 2] = c;
                    self.norm_rgba[di + 3] = a;
                }
            }
            self.upload_cursor_texture(device, context, w, h, 1);
        }
    }

    unsafe fn seed_from_win32_if_needed(
        &mut self,
        device: &ID3D11Device,
        context: &ID3D11DeviceContext,
        cap_left: i32,
        cap_top: i32,
    ) {
        if self.seen_dxgi_mouse || self.has_shape {
            return;
        }
        let mut ci = CURSORINFO {
            cbSize: std::mem::size_of::<CURSORINFO>() as u32,
            ..Default::default()
        };
        if GetCursorInfo(&mut ci).is_err()
            || (ci.flags.0 & CURSOR_SHOWING.0) == 0
            || ci.hCursor.is_invalid()
        {
            return;
        }
        let hicon = HICON(ci.hCursor.0);
        let mut ii = ICONINFO::default();
        if GetIconInfo(hicon, &mut ii).is_err() {
            return;
        }
        let mut bmp = BITMAP::default();
        let target_bm = if !ii.hbmColor.is_invalid() {
            ii.hbmColor
        } else {
            ii.hbmMask
        };
        let got_obj = GetObjectW(
            HGDIOBJ(target_bm.0),
            std::mem::size_of::<BITMAP>() as i32,
            Some(&mut bmp as *mut _ as *mut _),
        );
        let cw = if got_obj > 0 && bmp.bmWidth > 0 {
            bmp.bmWidth as u32
        } else {
            32
        };
        let ch = if got_obj > 0 && bmp.bmHeight > 0 {
            if ii.hbmColor.is_invalid() {
                (bmp.bmHeight / 2).max(1) as u32
            } else {
                bmp.bmHeight as u32
            }
        } else {
            32
        };
        self.pos_x = ci.ptScreenPos.x - cap_left - ii.xHotspot as i32;
        self.pos_y = ci.ptScreenPos.y - cap_top - ii.yHotspot as i32;
        if !ii.hbmMask.is_invalid() {
            let _ = DeleteObject(ii.hbmMask);
        }
        if !ii.hbmColor.is_invalid() {
            let _ = DeleteObject(ii.hbmColor);
        }

        if let Some(rgba) = render_hcursor_premult_bgra(hicon, cw, ch) {
            self.norm_rgba = rgba;
            self.visible = true;
            self.upload_cursor_texture(device, context, cw, ch, 0);
        }
    }

    pub unsafe fn composite_onto_target(
        &mut self,
        device: &ID3D11Device,
        context: &ID3D11DeviceContext,
        dst_tex: &ID3D11Texture2D,
        dst_rtv: &ID3D11RenderTargetView,
        cap_w: u32,
        cap_h: u32,
        cap_left: i32,
        cap_top: i32,
        offset_x: i32,
        offset_y: i32,
    ) {
        if !self.seen_dxgi_mouse {
            self.seed_from_win32_if_needed(device, context, cap_left, cap_top);
        }
        if !self.visible || !self.has_shape || self.shape_w == 0 || self.shape_h == 0 {
            return;
        }

        let draw_x = self.pos_x + offset_x;
        let draw_y = self.pos_y + offset_y;
        let vp_l = draw_x.clamp(0, cap_w as i32) as u32;
        let vp_t = draw_y.clamp(0, cap_h as i32) as u32;
        let vp_r = (draw_x + self.shape_w as i32).clamp(0, cap_w as i32) as u32;
        let vp_b = (draw_y + self.shape_h as i32).clamp(0, cap_h as i32) as u32;
        if vp_r <= vp_l || vp_b <= vp_t {
            return;
        }

        let vw = vp_r - vp_l;
        let vh = vp_b - vp_t;
        if !self.ensure_bg_patch(device, vw, vh) {
            return;
        }
        let (Some(ref cur_srv), Some(ref bg_tex), Some(ref bg_srv)) =
            (&self.cur_srv, &self.bg_tex, &self.bg_srv)
        else {
            return;
        };

        let src_box = D3D11_BOX {
            left: vp_l,
            top: vp_t,
            front: 0,
            right: vp_r,
            bottom: vp_b,
            back: 1,
        };
        context.CopySubresourceRegion(bg_tex, 0, 0, 0, 0, dst_tex, 0, Some(&src_box));

        let cb_val = CursorCb {
            rect_info: [draw_x, draw_y, vp_l as i32, vp_t as i32],
            mode_info: [self.shape_kind, 0, 0, 0],
        };
        context.UpdateSubresource(
            &self.cb,
            0,
            None,
            &cb_val as *const _ as *const _,
            0,
            0,
        );

        let vp = D3D11_VIEWPORT {
            TopLeftX: vp_l as f32,
            TopLeftY: vp_t as f32,
            Width: vw as f32,
            Height: vh as f32,
            MinDepth: 0.0,
            MaxDepth: 1.0,
        };

        context.IASetInputLayout(None);
        context.IASetPrimitiveTopology(D3D11_PRIMITIVE_TOPOLOGY_TRIANGLESTRIP);
        context.VSSetShader(&self.vs, None);
        context.PSSetShader(&self.ps, None);
        context.PSSetConstantBuffers(0, Some(&[Some(self.cb.clone())]));
        context.PSSetShaderResources(0, Some(&[Some(cur_srv.clone()), Some(bg_srv.clone())]));
        context.RSSetState(&self.rs);
        context.RSSetViewports(Some(&[vp]));
        context.OMSetBlendState(None, None, 0xFFFF_FFFF);
        context.OMSetRenderTargets(Some(&[Some(dst_rtv.clone())]), None);
        context.Draw(4, 0);

        context.OMSetRenderTargets(None, None);
        context.PSSetShaderResources(0, Some(&[None, None]));
    }
}

unsafe fn render_hcursor_premult_bgra(hicon: HICON, w: u32, h: u32) -> Option<Vec<u8>> {
    if w == 0 || h == 0 || w > 256 || h > 256 {
        return None;
    }
    let bmi = BITMAPINFO {
        bmiHeader: BITMAPINFOHEADER {
            biSize: std::mem::size_of::<BITMAPINFOHEADER>() as u32,
            biWidth: w as i32,
            biHeight: -(h as i32),
            biPlanes: 1,
            biBitCount: 32,
            biCompression: BI_RGB.0,
            ..Default::default()
        },
        ..Default::default()
    };
    let dc = CreateCompatibleDC(None);
    if dc.0.is_null() {
        return None;
    }
    let mut b_ptr: *mut c_void = null_mut();
    let mut w_ptr: *mut c_void = null_mut();
    let bmp_b = CreateDIBSection(dc, &bmi, DIB_RGB_COLORS, &mut b_ptr, None, 0).unwrap_or_default();
    let bmp_w = CreateDIBSection(dc, &bmi, DIB_RGB_COLORS, &mut w_ptr, None, 0).unwrap_or_default();
    if bmp_b.0.is_null() || bmp_w.0.is_null() || b_ptr.is_null() || w_ptr.is_null() {
        if !bmp_b.0.is_null() {
            let _ = DeleteObject(bmp_b);
        }
        if !bmp_w.0.is_null() {
            let _ = DeleteObject(bmp_w);
        }
        let _ = DeleteDC(dc);
        return None;
    }

    let rc = RECT { left: 0, top: 0, right: w as i32, bottom: h as i32 };
    let old = SelectObject(dc, HGDIOBJ(bmp_b.0));
    let black_br = HBRUSH(GetStockObject(BLACK_BRUSH).0);
    let _ = FillRect(dc, &rc, black_br);
    let _ = DrawIconEx(dc, 0, 0, hicon, w as i32, h as i32, 0, None, DI_NORMAL);

    SelectObject(dc, HGDIOBJ(bmp_w.0));
    let white_br = HBRUSH(GetStockObject(WHITE_BRUSH).0);
    let _ = FillRect(dc, &rc, white_br);
    let _ = DrawIconEx(dc, 0, 0, hicon, w as i32, h as i32, 0, None, DI_NORMAL);

    SelectObject(dc, old);

    let px_count = (w * h) as usize;
    let b_sl = std::slice::from_raw_parts(b_ptr as *const u8, px_count * 4);
    let w_sl = std::slice::from_raw_parts(w_ptr as *const u8, px_count * 4);
    let mut out = vec![0u8; px_count * 4];
    for i in 0..px_count {
        let off = i * 4;
        let b0 = b_sl[off] as i32;
        let g0 = b_sl[off + 1] as i32;
        let r0 = b_sl[off + 2] as i32;
        let b1 = w_sl[off] as i32;
        let g1 = w_sl[off + 1] as i32;
        let r1 = w_sl[off + 2] as i32;
        let diff = ((b1 - b0) + (g1 - g0) + (r1 - r0)) / 3;
        if diff < -32 {
            // XOR / inverted cursor pixel fallback: render crisp high-contrast pixel
            out[off] = 240;
            out[off + 1] = 240;
            out[off + 2] = 240;
            out[off + 3] = 255;
        } else {
            let a = (255 - diff).clamp(0, 255) as u8;
            out[off] = b0.clamp(0, 255) as u8;
            out[off + 1] = g0.clamp(0, 255) as u8;
            out[off + 2] = r0.clamp(0, 255) as u8;
            out[off + 3] = a;
        }
    }

    let _ = DeleteObject(bmp_b);
    let _ = DeleteObject(bmp_w);
    let _ = DeleteDC(dc);
    Some(out)
}

/// GPU shader self-test for DXGI cursor compositor + GDI fallback helper.
pub fn verify_cursor_compositor() -> (bool, String) {
    unsafe {
        let mut dev_opt = None;
        let mut ctx_opt = None;
        let levels = [D3D_FEATURE_LEVEL_11_0];
        if D3D11CreateDevice(
            None,
            D3D_DRIVER_TYPE_HARDWARE,
            HMODULE::default(),
            D3D11_CREATE_DEVICE_BGRA_SUPPORT,
            Some(&levels),
            D3D11_SDK_VERSION,
            Some(&mut dev_opt),
            None,
            Some(&mut ctx_opt),
        )
        .is_err()
        {
            return (false, "Cursor Test FAIL: D3D11CreateDevice failed".to_string());
        }
        let (Some(device), Some(context)) = (dev_opt, ctx_opt) else {
            return (false, "Cursor Test FAIL: missing D3D11 device/context".to_string());
        };
        let Some(mut comp) = DxgiCursorCompositor::new(&device) else {
            return (false, "Cursor Test FAIL: DxgiCursorCompositor::new failed".to_string());
        };

        let w = 128u32;
        let h = 128u32;
        let mut init_bg = vec![0u8; (w * h * 4) as usize];
        for i in 0..(w * h) as usize {
            init_bg[i * 4] = 80;      // B
            init_bg[i * 4 + 1] = 80;  // G
            init_bg[i * 4 + 2] = 80;  // R
            init_bg[i * 4 + 3] = 255; // A
        }
        let desc = D3D11_TEXTURE2D_DESC {
            Width: w,
            Height: h,
            MipLevels: 1,
            ArraySize: 1,
            Format: DXGI_FORMAT_B8G8R8A8_UNORM,
            SampleDesc: DXGI_SAMPLE_DESC { Count: 1, Quality: 0 },
            Usage: D3D11_USAGE_DEFAULT,
            BindFlags: (D3D11_BIND_SHADER_RESOURCE.0 | D3D11_BIND_RENDER_TARGET.0) as u32,
            ..Default::default()
        };
        let sdata = D3D11_SUBRESOURCE_DATA {
            pSysMem: init_bg.as_ptr() as *const _,
            SysMemPitch: w * 4,
            SysMemSlicePitch: w * h * 4,
        };
        let mut rt_tex = None;
        let _ = device.CreateTexture2D(&desc, Some(&sdata), Some(&mut rt_tex));
        let Some(rt_tex) = rt_tex else {
            return (false, "Cursor Test FAIL: target texture failed".to_string());
        };
        let mut rtv = None;
        let _ = device.CreateRenderTargetView(&rt_tex, None, Some(&mut rtv));
        let Some(rtv) = rtv else {
            return (false, "Cursor Test FAIL: RTV failed".to_string());
        };

        // Case 1: 16x16 bright green premultiplied arrow block + transparent border (kind=0)
        comp.seen_dxgi_mouse = true;
        comp.visible = true;
        comp.pos_x = 40;
        comp.pos_y = 40;
        comp.norm_rgba = vec![0u8; 16 * 16 * 4];
        for y in 2..12 {
            for x in 2..12 {
                let di = (y * 16 + x) * 4;
                comp.norm_rgba[di] = 20;
                comp.norm_rgba[di + 1] = 240;
                comp.norm_rgba[di + 2] = 30;
                comp.norm_rgba[di + 3] = 255;
            }
        }
        comp.upload_cursor_texture(&device, &context, 16, 16, 0);
        comp.composite_onto_target(&device, &context, &rt_tex, &rtv, w, h, 0, 0, 0, 0);

        // Case 2: 16x16 monochrome XOR cursor (kind=1, AND=1 + XOR=1 => invert RGB(80,80,80) -> (175,175,175))
        comp.pos_x = 80;
        comp.pos_y = 40;
        comp.norm_rgba = vec![0u8; 16 * 16 * 4];
        for y in 0..16 {
            for x in 0..16 {
                let di = (y * 16 + x) * 4;
                if (4..12).contains(&x) && (4..12).contains(&y) {
                    comp.norm_rgba[di] = 255;
                    comp.norm_rgba[di + 1] = 255;
                    comp.norm_rgba[di + 2] = 255;
                    comp.norm_rgba[di + 3] = 255;
                } else {
                    comp.norm_rgba[di + 3] = 255; // transparent (AND=1, XOR=0)
                }
            }
        }
        comp.upload_cursor_texture(&device, &context, 16, 16, 1);
        comp.composite_onto_target(&device, &context, &rt_tex, &rtv, w, h, 0, 0, 0, 0);

        // Case 3: GDI BitBlt fallback helper smoke test on 64x64 DIBSection
        let bmi = BITMAPINFO {
            bmiHeader: BITMAPINFOHEADER {
                biSize: std::mem::size_of::<BITMAPINFOHEADER>() as u32,
                biWidth: 64,
                biHeight: -64,
                biPlanes: 1,
                biBitCount: 32,
                biCompression: BI_RGB.0,
                ..Default::default()
            },
            ..Default::default()
        };
        let gdi_dc = CreateCompatibleDC(None);
        let mut gdi_bits: *mut c_void = null_mut();
        let gdi_bmp = CreateDIBSection(gdi_dc, &bmi, DIB_RGB_COLORS, &mut gdi_bits, None, 0)
            .unwrap_or_default();
        if !gdi_dc.0.is_null() && !gdi_bmp.0.is_null() {
            let old = SelectObject(gdi_dc, HGDIOBJ(gdi_bmp.0));
            draw_cursor_on_gdi_dc(gdi_dc, 0, 0, 64, 64);
            SelectObject(gdi_dc, old);
        }
        if !gdi_bmp.0.is_null() {
            let _ = DeleteObject(gdi_bmp);
        }
        if !gdi_dc.0.is_null() {
            let _ = DeleteDC(gdi_dc);
        }

        // Staging readback for automated pixel verification
        let st_desc = D3D11_TEXTURE2D_DESC {
            Width: w,
            Height: h,
            MipLevels: 1,
            ArraySize: 1,
            Format: DXGI_FORMAT_B8G8R8A8_UNORM,
            SampleDesc: DXGI_SAMPLE_DESC { Count: 1, Quality: 0 },
            Usage: D3D11_USAGE_STAGING,
            CPUAccessFlags: D3D11_CPU_ACCESS_READ.0 as u32,
            MiscFlags: D3D11_RESOURCE_MISC_FLAG(0).0 as u32,
            ..Default::default()
        };
        let mut st_tex = None;
        let _ = device.CreateTexture2D(&st_desc, None, Some(&mut st_tex));
        let Some(st_tex) = st_tex else {
            return (false, "Cursor Test FAIL: staging readback texture failed".to_string());
        };
        context.CopyResource(&st_tex, &rt_tex);

        let mut mapped = D3D11_MAPPED_SUBRESOURCE::default();
        if context.Map(&st_tex, 0, D3D11_MAP_READ, 0, Some(&mut mapped)).is_err() {
            return (false, "Cursor Test FAIL: Map failed".to_string());
        }
        let row_pitch = mapped.RowPitch as usize;
        let base = mapped.pData as *const u8;
        let px_inside = std::slice::from_raw_parts(base.add(45 * row_pitch + 45 * 4), 4);
        let px_mono_xor = std::slice::from_raw_parts(base.add(46 * row_pitch + 86 * 4), 4);
        let px_outside = std::slice::from_raw_parts(base.add(5 * row_pitch + 5 * 4), 4);
        let inside_rgb = (px_inside[2], px_inside[1], px_inside[0]);
        let mono_xor_rgb = (px_mono_xor[2], px_mono_xor[1], px_mono_xor[0]);
        let outside_rgb = (px_outside[2], px_outside[1], px_outside[0]);
        context.Unmap(&st_tex, 0);

        let pass = inside_rgb == (30, 240, 20)
            && mono_xor_rgb == (175, 175, 175)
            && outside_rgb == (80, 80, 80);
        let summary = format!(
            "Cursor GPU+GDI Test: color_rgb={:?} (exp (30,240,20)), mono_xor_rgb={:?} (exp (175,175,175)), outside_rgb={:?} (exp (80,80,80)) -> {}",
            inside_rgb,
            mono_xor_rgb,
            outside_rgb,
            if pass { "PASS" } else { "FAIL" }
        );
        (pass, summary)
    }
}
