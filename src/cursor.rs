/// Draw mouse cursor on GDI fallback DC cleanly using Win32 GetCursorInfo + DrawIconEx.
pub unsafe fn draw_cursor_on_gdi_dc(
    mem_dc: HDC,
    cap_left: i32,
    cap_top: i32,
    cap_w: i32,
    cap_h: i32,
) {
    let mut ci = CURSORINFO {
        cbSize: std::mem::size_of::<CURSORINFO>() as u32,
        ..Default::default()
    };
    if GetCursorInfo(&mut ci).is_err()
        || (ci.flags.0 & CURSOR_SHOWING.0) == 0
        || ci.hCursor.is_invalid()
    {
        return;
    }

    let hicon = HICON(ci.hCursor.0);
    let mut ii = ICONINFO::default();
    let (hx, hy) = if GetIconInfo(hicon, &mut ii).is_ok() {
        let hx = ii.xHotspot as i32;
        let hy = ii.yHotspot as i32;
        if !ii.hbmMask.is_invalid() {
            let _ = DeleteObject(ii.hbmMask);
        }
        if !ii.hbmColor.is_invalid() {
            let _ = DeleteObject(ii.hbmColor);
        }
        (hx, hy)
    } else {
        (0, 0)
    };

    let draw_x = ci.ptScreenPos.x - cap_left - hx;
    let draw_y = ci.ptScreenPos.y - cap_top - hy;
    if draw_x < -256 || draw_y < -256 || draw_x >= cap_w || draw_y >= cap_h {
        return;
    }

    let _ = DrawIconEx(mem_dc, draw_x, draw_y, hicon, 0, 0, 0, None, DI_NORMAL);
}

